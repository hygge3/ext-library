package ext.library.postgres.schema;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import ext.library.postgres.properties.PostgresProperties;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * 建表 DDL 生成测试：标识符（索引/触发器/函数名）不能带 schema 前缀，表引用必须带。
 */
@DisplayName("PostgreSQL 建表语句测试")
class PostgresSchemaStatementsTest {

    private static String joined(List<String> statements) {
        return String.join("\n", statements);
    }

    @Test
    void usesBareNamesWithoutSchema() {
        List<String> statements = PostgresSchemaInitializer.statements(new PostgresProperties());
        String sql = joined(statements);

        assertTrue(sql.contains("CREATE UNLOGGED TABLE IF NOT EXISTS pg_cache ("), sql);
        assertTrue(sql.contains("CREATE INDEX IF NOT EXISTS idx_pg_cache_expires ON pg_cache(expires_at)"), sql);
        assertTrue(sql.contains("CREATE OR REPLACE FUNCTION update_pg_cache_updated_at()"), sql);
        assertTrue(sql.contains("CREATE TRIGGER trg_pg_cache_updated_at"), sql);
        assertTrue(sql.contains("CREATE TABLE IF NOT EXISTS pg_jobs ("), sql);
        // 自增列用 identity，避免多出一个 pg_jobs_id_seq 序列对象
        assertTrue(sql.contains("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"), sql);
        assertFalse(sql.contains("BIGSERIAL"), sql);
        assertTrue(sql.contains("CREATE UNLOGGED TABLE IF NOT EXISTS pg_token_bucket ("), sql);
    }

    @Test
    void qualifiesTableReferencesOnly() {
        PostgresProperties properties = new PostgresProperties();
        properties.setSchema("middle");

        String sql = joined(PostgresSchemaInitializer.statements(properties));

        assertTrue(sql.startsWith("CREATE SCHEMA IF NOT EXISTS middle"), sql);
        // 表引用带前缀
        assertTrue(sql.contains("CREATE UNLOGGED TABLE IF NOT EXISTS middle.pg_cache ("), sql);
        assertTrue(sql.contains("ON middle.pg_cache(expires_at)"), sql);
        assertTrue(sql.contains("ON middle.pg_jobs(queue, scheduled_at)"), sql);
        assertTrue(sql.contains("CREATE UNLOGGED TABLE IF NOT EXISTS middle.pg_token_bucket ("), sql);
        // 索引 / 触发器 / 函数名不带前缀，否则会生成 idx_middle.pg_cache_expires 这种非法标识符
        assertTrue(sql.contains("idx_pg_cache_expires"), sql);
        assertTrue(sql.contains("trg_pg_cache_updated_at"), sql);
        assertFalse(sql.contains("idx_middle."), sql);
        assertFalse(sql.contains("trg_middle."), sql);
        assertFalse(sql.contains("update_middle."), sql);
        assertTrue(sql.contains("CREATE OR REPLACE FUNCTION middle.update_pg_cache_updated_at()"), sql);
        assertTrue(sql.contains("EXECUTE FUNCTION middle.update_pg_cache_updated_at()"), sql);
    }

    @Test
    void skipsEverythingWhenAllDisabled() {
        PostgresProperties properties = new PostgresProperties();
        properties.getCache().setAutoInitSchema(false);
        properties.getQueue().setAutoInitSchema(false);
        properties.getBucket().setAutoInitSchema(false);

        assertEquals(List.of(), PostgresSchemaInitializer.statements(properties));
    }
}
